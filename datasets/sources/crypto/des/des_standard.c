typedef struct {
    uint32_t round_keys[16][2];
} des_key_schedule;

static uint64_t permute(uint64_t in, const uint8_t *table, int n) {
    uint64_t out = 0;
    for (int i = 0; i < n; i++) {
        int bit = (in >> (64 - table[i])) & 1;
        out |= ((uint64_t)bit << (63 - i));
    }
    return out;
}

static uint32_t feistel_f(uint32_t R, const uint32_t k[2]) {
    uint64_t ER = 0;
    /* Expansion 32 -> 48 bits */
    for (int i = 0; i < 48; i++) {
        int bit_idx = (i % 6 == 0) ? (i == 0 ? 31 : (i/6)*4 - 1) : 
                      (i % 6 == 5) ? (i == 47 ? 0 : (i/6)*4 + 4) : 
                      ((i/6)*4 + (i%6) - 1);
        int bit = (R >> (31 - bit_idx)) & 1;
        ER |= ((uint64_t)bit << (47 - i));
    }
    uint64_t B = ER ^ (((uint64_t)k[0] << 32) | k[1]);
    uint32_t out = 0;
    for (int i = 0; i < 8; i++) {
        uint8_t chunk = (B >> (42 - 6*i)) & 0x3F;
        uint8_t row = ((chunk & 0x20) >> 4) | (chunk & 0x01);
        uint8_t col = (chunk >> 1) & 0x0F;
        uint8_t val = S_Boxes[i][row][col];
        out = (out << 4) | val;
    }
    return out;
}

void des_encrypt_block(const uint8_t in[8], const des_key_schedule *ks, uint8_t out[8]) {
    uint64_t block = 0;
    for (int i = 0; i < 8; i++) block = (block << 8) | in[i];
    block = permute(block, IP_Table, 64);

    uint32_t L = (uint32_t)(block >> 32);
    uint32_t R = (uint32_t)(block & 0xFFFFFFFF);

    for (int round = 0; round < 16; round++) {
        uint32_t next_R = L ^ feistel_f(R, ks->round_keys[round]);
        L = R;
        R = next_R;
    }

    uint64_t pre_fp = ((uint64_t)R << 32) | L;
    uint64_t final_block = permute(pre_fp, FP_Table, 64);

    for (int i = 7; i >= 0; i--) {
        out[i] = (uint8_t)(final_block & 0xFF);
        final_block >>= 8;
    }
}
